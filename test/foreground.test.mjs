import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { createForegroundMonitor } = require('../src/main/foreground.js');
let snapshot = { pid: 1, errorCode: 0, executablePath: 'C:\\Game\\game.exe', executableName: 'game.exe' };
const changes = [];
const monitor = createForegroundMonitor({ getForegroundProcess: () => snapshot }, state => changes.push(state));
monitor.poll();
assert.equal(changes.length, 1);
assert.equal(monitor.getStatus().available, true);
monitor.poll();
assert.equal(changes.length, 1, 'no duplicate notifications');
snapshot = { pid: 2, errorCode: 5, executablePath: null, executableName: null };
monitor.poll();
assert.equal(changes.length, 2);
assert.equal(monitor.getStatus().foreground.errorCode, 5);
snapshot = null;
monitor.poll();
assert.equal(monitor.getStatus().foreground, null);
const missing = createForegroundMonitor(null, () => assert.fail('missing provider must not emit'));
missing.poll();
assert.equal(missing.getStatus().available, false);
const broken = createForegroundMonitor({ getForegroundProcess() { throw new Error('native error'); } }, () => {});
broken.poll();
assert.match(broken.getStatus().error, /native error/);
monitor.start(); monitor.start(); monitor.stop(); monitor.stop();
console.log('PASS: foreground snapshots + native failure + idempotent lifecycle');
